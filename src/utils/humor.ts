export function getRandomQuote(trigger?: 'monday' | 'friday' | 'overtime' | 'underworked' | 'general'): HumorQuote {
  let list = HUMOR_QUOTES;
  if (trigger) {
    list = HUMOR_QUOTES.filter(q => q.trigger === trigger || q.trigger === 'general');
  }
  if (list.length === 0) list = HUMOR_QUOTES;
  return list[Math.floor(Math.random() * list.length)];
}

export function getTrackingHumor(spent: number, estimated: number): { status: string; subtext: string; colorClass: string } {
  if (estimated === 0) {
    return {
      status: "Untracked Abyss",
      subtext: "No budget set. Infinite hours detected. Finance is crying.",
      colorClass: "text-slate-500 bg-slate-50 border-slate-200 dark:bg-zinc-800/50 dark:border-zinc-700/50"
    };
  }

  const ratio = spent / estimated;

  if (ratio === 0) {
    return {
      status: "Pris-tine Slacking",
      subtext: "0% spent. Are we even employed here?",
      colorClass: "text-blue-600 bg-blue-50 border-blue-200 dark:bg-blue-950/20 dark:border-blue-900/30 dark:text-blue-400"
    };
  } else if (ratio < 0.3) {
    return {
      status: "Suspiciously Safe",
      subtext: `${Math.round(ratio * 100)}% spent. You're working too slowly or typing too fast.`,
      colorClass: "text-teal-600 bg-teal-50 border-teal-200 dark:bg-teal-950/20 dark:border-teal-900/30 dark:text-teal-400"
    };
  } else if (ratio < 0.75) {
    return {
      status: "Cruising Altitude",
      subtext: `${Math.round(ratio * 100)}% spent. Standard operating efficiency. No eye contact.`,
      colorClass: "text-emerald-600 bg-emerald-50 border-emerald-200 dark:bg-emerald-950/20 dark:border-emerald-900/30 dark:text-emerald-400"
    };
  } else if (ratio <= 1.0) {
    return {
      status: "Approaching Redline",
      subtext: `${Math.round(ratio * 100)}% spent. Prepare the 'sudden scope change' excuse.`,
      colorClass: "text-amber-600 bg-amber-50 border-amber-200 dark:bg-amber-950/20 dark:border-amber-900/30 dark:text-amber-400"
    };
  } else {
    const overPct = Math.round((ratio - 1) * 100);
    return {
      status: "Infinite Expansion",
      subtext: `${overPct}% over budget! Congratulations, you have achieved Senior Consultant status.`,
      colorClass: "text-rose-600 bg-rose-50 border-rose-200 dark:bg-rose-950/20 dark:border-rose-900/30 dark:text-rose-400"
    };
  }
}
